import streamlit as st

st.set_page_config(
    page_title="โทษของสุรา",
    page_icon="🍺"
)

st.title("🍺 โทษและอันตรายของสุรา (แอลกอฮอล์)")

st.image("https://images.unsplash.com/photo-1582451156358-e4fcc8915830?crop=entropy&cs=tinysrgb&fit=max&fm=jpg&ixid=M3wzNTU2NHwwfDF8c2VhcmNofDh8fGFsY29ob2wlMjByaXNrfGVufDB8fHx8MTcwMDYyOTE1MHww&ixlib=rb-4.0.3&q=80&w=1080",
         caption="การดื่มสุราส่งผลเสียต่ออวัยวะหลายส่วน")

st.markdown("""
การดื่มเครื่องดื่มแอลกอฮอล์ในปริมาณมากและต่อเนื่อง
ส่งผลกระทบต่อร่างกายทั้งในระยะสั้นและระยะยาว
""")

tab1, tab2 = st.tabs(["ผลกระทบระยะสั้น (Short-Term)", "ผลกระทบระยะยาว (Long-Term)"])

with tab1:
    st.subheader("ผลกระทบระยะสั้น")
    st.markdown("""
    * **สูญเสียการควบคุม:** การตอบสนองช้าลง, การตัดสินใจแย่ลง, พูดไม่ชัด
    * **การมองเห็น:** ภาพพร่ามัว
    * **อุบัติเหตุ:** เพิ่มความเสี่ยงต่อการเกิดอุบัติเหตุบนท้องถนนหรือการทะเลาะวิวาท
    * **หมดสติ:** การดื่มเร็วเกินไปอาจทำให้หมดสติ หรือเกิดภาวะแอลกอฮอล์เป็นพิษเฉียบพลัน
    * **สูญเสียความทรงจำ:** อาจจำเหตุการณ์ที่เกิดขึ้นระหว่างเมาไม่ได้ (Blackout)
    """)

with tab2:
    st.subheader("ผลกระทบระยะยาว")
    st.markdown("""
    * **โรคตับ:** ไขมันพอกตับ, ตับอักเสบ และนำไปสู่โรคตับแข็งในที่สุด
    * **โรคสมอง:** สมองเสื่อม, ความจำแย่ลง, การเรียนรู้ลดลง
    * **โรคหัวใจและหลอดเลือด:** ความดันโลหิตสูง, หัวใจเต้นผิดจังหวะ, กล้ามเนื้อหัวใจเสื่อม
    * **โรคมะเร็ง:** เพิ่มความเสี่ยงมะเร็งช่องปาก, ลำคอ, ตับ และเต้านม
    * **โรคตับอ่อนอักเสบ:** ทำให้ปวดท้องอย่างรุนแรงและย่อยอาหารได้ไม่ดี
    * **การเสพติด:** ภาวะติดสุรา (Alcoholism) ที่ต้องพึ่งพาแอลกอฮอล์ทั้งร่างกายและจิตใจ
    """)

st.error("**คำเตือน:** การดื่มสุราเป็นประจำ แม้ในปริมาณไม่มาก ก็สามารถนำไปสู่การเสพติดและปัญหาสุขภาพร้ายแรงได้")
